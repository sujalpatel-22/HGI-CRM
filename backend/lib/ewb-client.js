'use strict';
/**
 * NIC e-Way Bill System client (ewaybillgst.gov.in API, v1.03) — for e-way bills
 * on invoices that do not have an IRN, and for Part-B (vehicle) updates,
 * transporter updates and validity extension, which the IRP does not offer.
 *
 * Auth: { action:"ACCESSTOKEN", username, password: RSA(password), app_key: RSA(appKey) }
 * POST: { action, data: AES_SEK(json) }   GET: response { data, rek, hmac }
 */
const crypto = require('crypto');
const { loadPublicKey, rsaEncrypt, aesEncrypt, aesDecrypt, parsePayload, hmacOk } = require('./nic-crypto');
const { ApiError, requestJson } = require('./nic-http');

function ewbErrors(json) {
  let e = json.error ?? json.errorCodes ?? json.message;
  if (typeof e === 'string') {
    try { e = JSON.parse(Buffer.from(e, 'base64').toString('utf8')); } catch { try { e = JSON.parse(e); } catch { e = { message: e }; } }
  }
  const codes = String(e?.errorCodes ?? e?.errorCode ?? '').split(',').map(s => s.trim()).filter(Boolean);
  if (codes.length) return codes.map(c => ({ code: c, message: EWB_ERRORS[c] || 'e-Way Bill error ' + c }));
  return [{ code: '', message: e?.message || 'e-Way Bill request failed' }];
}

// Most common e-Way Bill error codes (full list: NIC e-Way Bill API docs)
const EWB_ERRORS = {
  '106': 'Invalid token / session expired', '108': 'Invalid login credentials', '238': 'Invalid auth token',
  '312': 'This e-way bill was generated by another user or is not yours', '315': 'Validity of e-way bill has expired',
  '316': 'Enter a valid vehicle number', '338': 'You cannot update transporter for this e-way bill',
  '362': 'Distance between PIN codes exceeds the allowed limit', '601': 'Invalid e-way bill number',
  '604': 'E-way bill already cancelled', '613': 'E-way bill cannot be cancelled after 24 hours',
  '702': 'The distance between the PIN codes given is too high or too low', '714': 'Vehicle number not in proper format'
};

class EwbClient {
  constructor(cfg, { timeoutMs = 30000, logger = () => {} } = {}) {
    this.cfg = cfg; this.timeoutMs = timeoutMs; this.log = logger;
    this.publicKey = cfg.publicKeyObj || loadPublicKey(cfg.publicKey);
    this.session = null; this.authInFlight = null;
  }
  baseHeaders() {
    return { 'client-id': this.cfg.clientId, 'client-secret': this.cfg.clientSecret, gstin: this.cfg.gstin, ...this.cfg.extraHeaders };
  }
  async authenticate(force = false) {
    if (!force && this.session && Date.now() < this.session.expiresAt) return this.session;
    if (this.authInFlight) return this.authInFlight;
    this.authInFlight = (async () => {
      const appKey = crypto.randomBytes(32);
      const appKeyPlain = this.cfg.appKeyRsaInput === 'base64' ? Buffer.from(appKey.toString('base64')) : appKey;
      const body = {
        action: 'ACCESSTOKEN', username: this.cfg.username,
        password: rsaEncrypt(this.publicKey, Buffer.from(this.cfg.password)),
        app_key: rsaEncrypt(this.publicKey, appKeyPlain)
      };
      const { json } = await requestJson('POST', this.cfg.baseUrl + this.cfg.paths.auth, { headers: this.baseHeaders(), body, timeoutMs: this.timeoutMs });
      if (String(json.status) !== '1' || !json.authtoken || !json.sek) {
        const errors = ewbErrors(json);
        throw new ApiError('e-Way Bill login failed: ' + errors.map(e => `${e.code} ${e.message}`).join('; '), { code: 'EWB_AUTH_FAILED', errors });
      }
      const sek = aesDecrypt(appKey, json.sek);
      // Token valid 360 minutes from first login; refresh at 5h45m.
      this.session = { token: json.authtoken, sek, expiresAt: Date.now() + (5 * 60 + 45) * 60e3 };
      this.log({ event: 'ewb.auth', ok: true, env: this.cfg.env });
      return this.session;
    })();
    try { return await this.authInFlight; } finally { this.authInFlight = null; }
  }

  encodeData(sek, obj) {
    const json = Buffer.from(JSON.stringify(obj));
    return aesEncrypt(sek, this.cfg.dataEncoding === 'base64json' ? Buffer.from(json.toString('base64')) : json);
  }

  decodeResponse(s, json) {
    if (json.rek) {
      const rek = aesDecrypt(s.sek, json.rek);
      const dataBuf = aesDecrypt(rek, json.data);
      if (!hmacOk(rek, dataBuf, json.hmac)) throw new ApiError('e-Way Bill response failed integrity (HMAC) check', { code: 'EWB_BAD_HMAC' });
      return parsePayload(dataBuf);
    }
    return typeof json.data === 'string' ? parsePayload(aesDecrypt(s.sek, json.data)) : json.data;
  }

  async post(action, payload, retry = true) {
    const s = await this.authenticate();
    const headers = { ...this.baseHeaders(), authtoken: s.token };
    const { httpStatus, json } = await requestJson('POST', this.cfg.baseUrl + this.cfg.paths.action,
      { headers, body: { action, data: this.encodeData(s.sek, payload) }, timeoutMs: this.timeoutMs });
    if (String(json.status) === '1') return { data: this.decodeResponse(s, json), info: json.info };
    const errors = ewbErrors(json);
    if (retry && (httpStatus === 401 || errors.some(e => ['106', '238'].includes(e.code)))) { await this.authenticate(true); return this.post(action, payload, false); }
    throw new ApiError(errors.map(e => `${e.code ? e.code + ': ' : ''}${e.message}`).join('; '), { status: 422, code: 'EWB_REJECTED', errors, info: json.info });
  }

  async get(ewbNo, retry = true) {
    const s = await this.authenticate();
    const headers = { ...this.baseHeaders(), authtoken: s.token };
    const path = this.cfg.paths.get.replace('{ewbNo}', encodeURIComponent(ewbNo));
    const { httpStatus, json } = await requestJson('GET', this.cfg.baseUrl + path, { headers, timeoutMs: this.timeoutMs });
    if (String(json.status) === '1') return { data: this.decodeResponse(s, json) };
    const errors = ewbErrors(json);
    if (retry && (httpStatus === 401 || errors.some(e => ['106', '238'].includes(e.code)))) { await this.authenticate(true); return this.get(ewbNo, false); }
    throw new ApiError(errors.map(e => `${e.code ? e.code + ': ' : ''}${e.message}`).join('; '), { status: 422, code: 'EWB_REJECTED', errors });
  }

  generate(payload) { return this.post('GENEWAYBILL', payload); }
  cancel(ewbNo, reasonCode, remark) { return this.post('CANEWB', { ewbNo: Number(ewbNo), cancelRsnCode: Number(reasonCode), cancelRmrk: remark }); }
  updatePartB(p) { return this.post('VEHEWB', p); }
  updateTransporter(ewbNo, transporterId) { return this.post('UPDATETRANSPORTER', { ewbNo: Number(ewbNo), transporterId }); }
  extendValidity(p) { return this.post('EXTENDVALIDITY', p); }
}

module.exports = { EwbClient, EWB_ERRORS };
