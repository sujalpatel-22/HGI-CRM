#!/usr/bin/env node
// Builds the Google Apps Script web app (gas/dist/) from the SAME server modules the Cloud Run service uses.
//
//   node tools/build-gas.mjs            → gas/dist/Code.js + gas/dist/appsscript.json
//
// The modules are written for Node with async/await around Google calls. Apps Script cannot wait for a promise inside
// doPost/doGet, and its Google calls (Sheets advanced service, Utilities, LockService) are synchronous, so the build
// removes the async/await keywords: the same code then runs straight through. A module that would need a real promise
// (Promise.all, .then, timers) is refused here, so this never silently changes behaviour.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const lib = path.join(root, 'backend', 'lib');
const out = path.join(root, 'gas', 'dist');
const MODULES = ['sheets-client', 'sheet-db', 'sheets-schema', 'sheets-record-store', 'sheets-doc-store', 'accounts', 'router'];
const PAGES = ['index.html', 'privacy.html', 'delete-account.html'];

export function deAsync(src, name) {
  // the write queue in sheet-db.js is replaced on Apps Script (db.exclusive = script lock); everything else must be promise-free
  const body = name === 'sheet-db' ? src.replace(/this\.queue = Promise\.resolve\(\);/, 'this.queue = null;') : src;
  const bad = body.split('\n').map((l, i) => [i + 1, l]).filter(([, l]) => /Promise\.|\.then\(|\.catch\(|\bsetTimeout\b|\bsetInterval\b|for await/.test(l.replace(/\/\/.*$/, '')) && !/^\s*(\*|\/\/)/.test(l));
  const allowed = name === 'sheet-db' ? bad.filter(([, l]) => !/const run = this\.queue\.then|this\.queue = run\.catch/.test(l)) : bad;
  if (allowed.length) throw new Error(`${name}.js uses promises directly — cannot run on Apps Script:\n` + allowed.map(([n, l]) => `  ${n}: ${l.trim()}`).join('\n'));
  return body
    .replace(/\basync\s+function\b/g, 'function')
    .replace(/\basync\s+(\([^()]*\)\s*=>)/g, '$1')
    .replace(/\basync\s+([A-Za-z_$][\w$]*\s*=>)/g, '$1')
    .replace(/^(\s*)(static\s+)?async\s+([A-Za-z_$][\w$]*\s*\()/gm, '$1$2$3')
    .replace(/\bawait\s+/g, '');
}

export function build() {
  const parts = [`/* HGI Billing — Google Apps Script web app. GENERATED by tools/build-gas.mjs from backend/lib/*.js and gas/src/*.js —
 * do not edit here; change the sources and rebuild. */`];
  parts.push(fs.readFileSync(path.join(root, 'gas', 'src', 'runtime.js'), 'utf8'));
  for (const m of MODULES) {
    const src = deAsync(fs.readFileSync(path.join(lib, m + '.js'), 'utf8'), m);
    if (/\b(async|await)\b/.test(src.replace(/\/\*[\s\S]*?\*\/|\/\/.*$/gm, '').replace(/'(?:[^'\\]|\\.)*'|`(?:[^`\\]|\\.)*`/g, ''))) throw new Error(`${m}.js: async/await left after the transform`);
    parts.push(`__define(${JSON.stringify(m)}, function (module, exports, require) {\n${src}\n});`);
  }
  const pages = Object.fromEntries(PAGES.map(f => [f, fs.readFileSync(path.join(root, 'backend', 'public', f), 'utf8')]));
  parts.push(`var __PAGES = ${JSON.stringify(pages)};`);
  parts.push(fs.readFileSync(path.join(root, 'gas', 'src', 'main.js'), 'utf8'));
  fs.mkdirSync(out, { recursive: true });
  const code = parts.join('\n\n');
  fs.writeFileSync(path.join(out, 'Code.js'), code);
  fs.copyFileSync(path.join(root, 'gas', 'src', 'appsscript.json'), path.join(out, 'appsscript.json'));
  return { bytes: code.length, file: path.join(out, 'Code.js') };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const r = build();
  console.log(`gas/dist/Code.js written (${Math.round(r.bytes / 1024)} KB) + appsscript.json`);
}
